/**
 * Builds the contracts and copies the interface ABIs into shared/abi, where the web app, the
 * indexer and the SDK read them. `pnpm abi:check` fails when the committed copies are stale.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const INTERFACES = [
  { contract: 'ICore', exportName: 'coreAbi' },
  { contract: 'ICourt', exportName: 'courtAbi' },
  { contract: 'IVault', exportName: 'vaultAbi' },
  { contract: 'IFirewall', exportName: 'firewallAbi' },
] as const

const contractsDir = fileURLToPath(new URL('../../contracts/', import.meta.url))
const abiDir = fileURLToPath(new URL('../abi/', import.meta.url))

execFileSync('forge', ['build', '--root', contractsDir], { stdio: 'inherit' })

const abiOf = (contract: string): unknown[] => {
  const artifact = JSON.parse(readFileSync(`${contractsDir}out/${contract}.sol/${contract}.json`, 'utf8')) as { abi: unknown[] }
  return artifact.abi
}

for (const { contract } of INTERFACES) {
  writeFileSync(`${abiDir}${contract}.json`, `${JSON.stringify(abiOf(contract), null, 2)}\n`)
}

const header = '// Generated by shared/scripts/export-abi.ts from contracts/src/interfaces. Do not edit by hand.\n'
const abis = INTERFACES.map(
  ({ contract, exportName }) => `export const ${exportName} = ${JSON.stringify(abiOf(contract), null, 2)} as const\n`,
).join('\n')

const eip712 = `/**
 * Typed data a target's owner or deployer signs to name an Agent ID holder as publisher.
 * \`bindNonce\` is Core.bindNonce(target) at signing time; every binding consumes it.
 * Mirrors contracts/src/lib/BindTypes.sol; both are checked against rules/vectors/eip712.json.
 */
export const EIP712 = {
  /** Add \`chainId\` and \`verifyingContract\` (the Core address) when building the domain. */
  domain: { name: 'Sealflare', version: '1' },
  types: {
    BindByOwner: [
      { name: 'target', type: 'address' },
      { name: 'agentIdHolder', type: 'address' },
      { name: 'bindNonce', type: 'uint256' },
      { name: 'deadline', type: 'uint256' },
    ],
    BindByDeployer: [
      { name: 'target', type: 'address' },
      { name: 'deployer', type: 'address' },
      { name: 'deployNonce', type: 'uint256' },
      { name: 'agentIdHolder', type: 'address' },
      { name: 'bindNonce', type: 'uint256' },
      { name: 'deadline', type: 'uint256' },
    ],
  },
} as const
`

writeFileSync(`${abiDir}index.ts`, `${header}\n${abis}\n${eip712}`)
